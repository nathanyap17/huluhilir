const TABLES: Record<Lang, Record<StringKey, string>> = {
  ms,
  iba: ms, // unverified -- see file header
  en: en as unknown as Record<StringKey, string>,
};

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let text = TABLES[lang]?.[key] ?? ms[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  }
  return text;
}

/** `t("key", {vars})` in the farmer's chosen language; re-renders on change. */
export function useT() {
  const lang = (useSessionStore((s) => s.user?.language_pref) ?? "ms") as Lang;
  const t = useCallback(
    (key: StringKey, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang]
  );
  return { t, lang };
}
